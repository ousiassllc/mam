// strategyGuide explains the strategies to the Repair Agent.
var strategyGuide = map[domain.RepairAction]string{
	domain.RepairPrompt:              "the Shot Spec is revised for the issues; the model receives a better prompt",
	domain.RepairPartialRegeneration: "the Shot is generated again with the parts that were good (see preserve) kept exactly as they are",
	domain.RepairFullRetake:          "the same Shot Spec is generated again; use for random defects (flicker, artifacts) that a new draw can avoid",
	domain.RepairDifferentModel:      "the same Shot Spec is generated by the other video model; use when this model keeps failing the same way",
	domain.RepairReferenceReinforce:  "the reference images of the character/product are made more influential; use for identity, product shape or logo defects",
	domain.RepairEditLevel:           "the Take is kept and the flawed time ranges are cut or covered in the edit; use for short, minor defects",
}

const systemPrompt = `You are the Repair Agent of an AI video production team.
An AI Video Judge rejected a generated video Take. Choose the ONE repair strategy that most likely produces a usable Take next, from the candidates you are given. Think about what the issues have in common: the same defect that survived an earlier strategy needs a different one.

Return ONLY one JSON object:
{"action": "one of the candidate identifiers",
 "reason": "one short English sentence",
 "instructions": ["snake_case_instruction such as reduce_camera_speed_40_percent"]}

Rules:
- "action" MUST be one of the candidates.
- "instructions" are optional extra directions for the regeneration, in snake_case English; do not repeat the Judge's instructions.
- Write English only.`

// answer is the JSON the Repair Agent returns.
type answer struct {
	Action       string   `json:"action"`
	Reason       string   `json:"reason"`
	Instructions []string `json:"instructions"`
}

// Choice is the Repair Agent's decision.
type Choice struct {
	Action       domain.RepairAction
	Reason       string
	Instructions []string
}

// choose asks the Reasoning LLM (AgentRepair) which of the candidates to use. An answer that is not
// a candidate is an error wrapping planning.ErrInvalidPlan (it is never used).
func choose(ctx context.Context, c llm.Completer, s Situation, candidates []domain.RepairAction) (Choice, error) {
	ans, err := llm.CompleteJSON[answer](ctx, c, llm.AgentRepair, llm.Request{System: systemPrompt, User: userPrompt(s, candidates)})
	if err != nil {
		return Choice{}, err
	}
	action := domain.RepairAction(identifier(ans.Action))
	if !slices.Contains(candidates, action) {
		return Choice{}, fmt.Errorf("repair: %w: %q is not a candidate", planning.ErrInvalidPlan, ans.Action)
	}
	return Choice{Action: action, Reason: strings.TrimSpace(ans.Reason), Instructions: identifiers(ans.Instructions)}, nil
}

func userPrompt(s Situation, candidates []domain.RepairAction) string {
	var b strings.Builder
	b.WriteString("JUDGE RESULT:\n")
	view := struct {
		Result   domain.JudgeVerdict    `json:"result"`
		Issues   []domain.JudgeIssue    `json:"issues"`
		Preserve []string               `json:"preserve"`
		Judge    *domain.RepairStrategy `json:"judge_recommendation,omitempty"`
	}{s.Result.Result, s.Result.Issues, s.Result.Preserve, s.Result.RepairStrategy}
	raw, _ := json.MarshalIndent(view, "", "  ")
	b.Write(raw)
	b.WriteString("\n\nCANDIDATES:")
	for _, a := range candidates {
		fmt.Fprintf(&b, "\n- %s: %s", a, strategyGuide[a])
	}
	if len(s.Tried) > 0 {
		names := make([]string, len(s.Tried))
		for i, a := range s.Tried {
			names[i] = string(a)
		}
		fmt.Fprintf(&b, "\n\nALREADY TRIED on this shot (they did not give a usable Take): %s", strings.Join(names, ", "))
	}
	return b.String()
}

var nonIdentifier = regexp.MustCompile(`[^a-z0-9]+`)

// identifier turns "Reduce Camera-Speed" into "reduce_camera_speed" ("" when nothing is left).
func identifier(s string) string {
	return strings.Trim(nonIdentifier.ReplaceAllString(strings.ToLower(strings.TrimSpace(s)), "_"), "_")
}

// identifiers cleans a list of instructions and drops duplicates and empty ones.
func identifiers(list []string) []string {
	var out []string
	for _, s := range list {
		if id := identifier(s); id != "" && !slices.Contains(out, id) {
			out = append(out, id)
		}
	}
	return out
}
