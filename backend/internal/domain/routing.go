package domain

// RoutingMode is how the video model of a Take was chosen (spec/architecture/model-adapters.md §12).
type RoutingMode string

// Routing modes.
const (
	// RoutingAdaptive: Multi-model routing replaced the Quality Policy's primary model.
	RoutingAdaptive RoutingMode = "adaptive"
	// RoutingPolicyDefault: challengers were compared and the Quality Policy's assignment stayed.
	RoutingPolicyDefault RoutingMode = "policy_default"
	// RoutingFixed: the user fixed the Video Model of the Shot (MANUAL or LOCK).
	RoutingFixed RoutingMode = "fixed"
	// RoutingDisabled: Multi-model routing is switched off in the configuration.
	RoutingDisabled RoutingMode = "disabled"
)

// Reasons a candidate was not routed to (RoutingCandidate.Excluded).
const (
	ExcludedCircuitOpen          = "circuit_open"          // the vendor's circuit breaker is open
	ExcludedNoBackend            = "no_backend"            // no API backend for the model
	ExcludedInsufficientEvidence = "insufficient_evidence" // fewer Judged Takes than min_samples
	ExcludedBelowMinimumScore    = "below_minimum_score"   // average score under the Minimum acceptance score
	ExcludedMargin               = "margin"                // not better than the anchor by the switch margin
	ExcludedOutscored            = "outscored"             // eligible, but another challenger scored higher
)

// ModelRecord is what the Judge found about the Takes one video model made in a Project: the mean of
// each score axis (0-100) and the share of Takes whose latest Judge result passed.
type ModelRecord struct {
	Model ModelName `json:"model"`
	// Samples is the number of Takes that have a Judge result.
	Samples  int        `json:"samples"`
	Scores   TakeScores `json:"mean_scores"`
	PassRate float64    `json:"pass_rate"`
}

// RoutingCandidate is one video model weighed by Multi-model routing.
type RoutingCandidate struct {
	Model      ModelName `json:"model"`
	Resolution string    `json:"resolution"`
	// Anchor is true for the primary model of the Quality Policy.
	Anchor bool `json:"anchor,omitempty"`
	// Samples, MeanScore (axis means weighted by the Shot's axis weights, 0-100) and PassRate are the
	// Judge record the candidate was weighed by; Samples is 0 without a record.
	Samples   int     `json:"samples"`
	MeanScore float64 `json:"mean_score,omitempty"`
	PassRate  float64 `json:"pass_rate,omitempty"`
	// CostPerTake is the estimated cost of one Take (USD).
	CostPerTake float64 `json:"cost_per_take"`
	Quality     float64 `json:"quality"`
	Cost        float64 `json:"cost"`
	Fit         float64 `json:"fit"`
	Score       float64 `json:"score"`
	// Excluded is why the candidate was not chosen ("" for the anchor and for the chosen model).
	Excluded string `json:"excluded,omitempty"`
}

// RoutingModel is a video model at a resolution as the routing records it.
type RoutingModel struct {
	Model      ModelName `json:"model"`
	Resolution string    `json:"resolution"`
}

// RoutingDecision is why a Take was generated by the video model it was (F-27, spec/spec.md §29.3):
// stored in take.model_parameters.routing and shown in the Generation Trace.
type RoutingDecision struct {
	Mode RoutingMode `json:"mode"`
	// PolicyPrimary and PolicyFallback are the Quality Policy's assignment; Primary and Fallback
	// what the Take was generated with (the model that actually made it can differ: see FellBack of
	// the Take).
	PolicyPrimary  RoutingModel `json:"policy_primary"`
	PolicyFallback RoutingModel `json:"policy_fallback"`
	Primary        RoutingModel `json:"primary"`
	Fallback       RoutingModel `json:"fallback"`
	// Reason is the decision in one sentence.
	Reason string `json:"reason"`
	// AxisWeights are the weights of the four score axes the Shot's nature gave (sum 1); nil unless
	// candidates were compared.
	AxisWeights *TakeScores        `json:"axis_weights,omitempty"`
	Candidates  []RoutingCandidate `json:"candidates,omitempty"`
}
